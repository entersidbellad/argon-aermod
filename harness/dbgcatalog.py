#!/usr/bin/env python3
"""Write the DEBUGOPT variable catalogue from real reference runs.

  make debug-refs                         # DEBUGOPT runs of DEFAULT_CASES into out/ref_debug
  python harness/dbgcatalog.py            # -> prompts/debug_vars.md, harness/debug_vars.json

Every name in the catalogue is a record dbgparse.py read out of a *.DBG file
written by our compiled AERMOD 26135; nothing is typed in by hand. Fails if any
numeric line in those files was not parsed (see dbgparse.IGNORED_TEMPLATES).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

import cases as catalog
import dbgparse

DEFAULT_CASES = ["aertest_nobldg", "CAPPED_STACK2CE", "AERTEST", "CAPPED_STACK1C0", "ALLSRCS_STACKDW"]
JSON_OUT = Path(__file__).resolve().parent / "debug_vars.json"
MD_OUT = catalog.ROOT / "prompts" / "debug_vars.md"
FILE_OF = {"METDEB": "METEOR.DBG"}


def level(rec: dbgparse.Record) -> str:
    if rec.sub == "METDEB":
        if rec.irec == 0:
            return "hour"
        return "grid level" if rec.var.startswith("GRID") else "receptor"
    if rec.isrc == 0:
        return "hour"
    return "source-hour" if rec.irec == 0 else "source-receptor"


def build(case_names: list[str], who: str) -> list[dict]:
    seen: dict[tuple, dict] = {}
    for name in case_names:
        workdir = catalog.get(name).out_dir(who)
        skipped: dict = {}
        records = dbgparse.parse_dir(workdir, skipped)
        bad = {f: c for f, c in dbgparse.unexplained(skipped).items() if c}
        if bad:
            raise SystemExit(f"{name}: unparsed numeric lines {bad}")
        for rec in records:
            key = (rec.comp, rec.sub, rec.var)
            entry = seen.setdefault(key, {
                "file": "PRIME.DBG" if rec.comp == "PRIME" else FILE_OF.get(rec.sub, "MODEL.DBG"),
                "sub": rec.sub, "comp": rec.comp, "var": rec.var, "level": level(rec),
                "cases": []})
            if name not in entry["cases"]:
                entry["cases"].append(name)
    order = {"METEOR.DBG": 0, "MODEL.DBG": 1, "PRIME.DBG": 2}
    return sorted(seen.values(), key=lambda e: (order[e["file"]], e["sub"], e["comp"], e["var"]))


def markdown(entries: list[dict], case_names: list[str]) -> str:
    by_file: dict[str, list[dict]] = defaultdict(list)
    for e in entries:
        by_file[e["file"]].append(e)
    dotted = next(e["var"] for e in entries if "." in e["var"])
    operator = next(e["var"] for e in entries if any(c in e["var"] for c in "*/+-"))
    out = [
        "# DEBUGOPT variables (generated)",
        "",
        "Generated by `harness/dbgcatalog.py` from `CO DEBUGOPT MODEL METEOR [PRIME]` runs of",
        f"our compiled AERMOD 26135 on {', '.join(case_names)}. Do not edit by hand.",
        "",
        "Each row is one name `harness/dbgparse.py` reads from the Fortran WRITE statement",
        "in subroutine `sub`. `comp` is `PAN` (meander/pancake pass), `PLM` (coherent plume",
        f"pass), `PRIME`, or empty. Names with a dot (`{dotted}`) are a column of a",
        f"DEBOUT plume table row; names with an operator (`{operator}`) are the printed",
        "expression.",
        "",
    ]
    for f, rows in by_file.items():
        out += [f"## {f}", "", "| sub | comp | var | level | cases |", "|---|---|---|---|---|"]
        out += [f"| {e['sub']} | {e['comp']} | `{e['var']}` | {e['level']} | "
                f"{', '.join(e['cases'])} |" for e in rows]
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("cases", nargs="*", default=DEFAULT_CASES)
    ap.add_argument("--who", default="ref_debug", help="run directory under out/")
    args = ap.parse_args()
    entries = build(args.cases, args.who)
    JSON_OUT.write_text(json.dumps(entries, indent=1) + "\n")
    MD_OUT.write_text(markdown(entries, args.cases))
    print(f"{len(entries)} variables -> {MD_OUT.relative_to(catalog.ROOT)}, "
          f"{JSON_OUT.relative_to(catalog.ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
