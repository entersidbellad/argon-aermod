    Case("CAPPED_STACK2CE", "A", "epa", "capped.inp", "STACK2CE", "CAPPED_STACK2CE_01H.PST"),
    Case("HRDOW_STACK1", "A", "epa", "hrdow.inp", "STACK1", "HRDOW_STACK1_01H.PST",
         notes="Exercises EMISFACT HRDOW emission factors."),
