BY_NAME = {c.name: c for c in CASES}


def get(name: str) -> Case:
    try:
        return BY_NAME[name]
    except KeyError:
        raise SystemExit(f"unknown case {name!r}; known: {', '.join(BY_NAME)}") from None


def tier_cases(tier: str) -> list[Case]:
    """Cases the repair loop may run for a tier. Tier B includes tier A. Never the holdout."""
    if tier == "A":
        return [c for c in CASES if c.tier == "A"]
    if tier == "B":
        return [c for c in CASES if c.tier in ("A", "B")]
    raise ValueError(f"tier must be A or B, got {tier!r}")
